import mammoth from "mammoth";
import type { ParsedCsvResult } from "./excelCsvUtils";

export interface WordQuestionItem {
  nomor: string;
  jenis_soal: string;
  soal: string;
  opsi_a: string;
  opsi_b: string;
  opsi_c: string;
  opsi_d: string;
  opsi_e: string;
  kunci: string;
  bobot: string;
  toleransi: string;
  pembahasan: string;
}

/**
 * Standard headers for CBT questions import.
 */
export const QUESTION_IMPORT_HEADERS = [
  "nomor",
  "jenis_soal",
  "soal",
  "opsi_a",
  "opsi_b",
  "opsi_c",
  "opsi_d",
  "opsi_e",
  "kunci",
  "bobot",
  "toleransi",
  "pembahasan",
];

/**
 * Helper to normalize question type to system standards.
 */
export function normalizeWordQuestionType(rawType: string, optionsCount: number, key: string): string {
  const lower = rawType.toLowerCase().trim();
  if (lower.includes("mcma") || lower.includes("kompleks") || key.includes(",") || key.includes(";")) {
    return "multichoice_multi";
  }
  if (lower.includes("benar") || lower.includes("salah") || lower.includes("true") || lower.includes("false")) {
    return "truefalse";
  }
  if (lower.includes("isian") || lower.includes("singkat") || lower.includes("short")) {
    return "shortanswer";
  }
  if (lower.includes("numerik") || lower.includes("numerical") || lower.includes("angka")) {
    return "numerical";
  }
  if (lower.includes("esai") || lower.includes("essay") || lower.includes("uraian")) {
    return "essay";
  }
  if (lower.includes("jodoh") || lower.includes("match")) {
    return "match";
  }
  if (lower.includes("rumpang") || lower.includes("cloze") || lower.includes("gap")) {
    return "gapselect";
  }
  if (optionsCount > 0) {
    return "multichoice_single";
  }
  return "essay";
}

/**
 * Parses questions from table rows generated by mammoth HTML.
 */
function parseTableBasedQuestions(html: string): WordQuestionItem[] {
  const questions: WordQuestionItem[] = [];
  const tableMatches = html.match(/<table[\s\S]*?<\/table>/gi);
  if (!tableMatches) return questions;

  for (const tableHtml of tableMatches) {
    const rowMatches = tableHtml.match(/<tr[\s\S]*?<\/tr>/gi);
    if (!rowMatches || rowMatches.length <= 1) continue;

    // Header row
    const headers: string[] = [];
    const firstRowCells = rowMatches[0].match(/<t[hd][\s\S]*?<\/t[hd]>/gi) || [];
    for (const cell of firstRowCells) {
      headers.push(cell.replace(/<[^>]+>/g, "").trim().toLowerCase());
    }

    // Process data rows
    for (let r = 1; r < rowMatches.length; r++) {
      const cells = rowMatches[r].match(/<t[hd][\s\S]*?<\/t[hd]>/gi) || [];
      if (cells.length < 2) continue;

      const cellTexts = cells.map((c) =>
        c
          .replace(/<p>/gi, "")
          .replace(/<\/p>/gi, "<br/>")
          .replace(/<br\/?>$/gi, "")
          .trim(),
      );

      // Find matching indexes
      const getVal = (keywords: string[]): string => {
        for (let i = 0; i < headers.length; i++) {
          if (keywords.some((k) => headers[i].includes(k)) && cellTexts[i]) {
            return cellTexts[i];
          }
        }
        return "";
      };

      const nomor = getVal(["no", "nomor"]) || `${r}`;
      const soal = getVal(["soal", "pertanyaan", "stem", "narasi"]);
      if (!soal) continue;

      const opsi_a = getVal(["opsi_a", "opsi a", "pilihan a", "a"]);
      const opsi_b = getVal(["opsi_b", "opsi b", "pilihan b", "b"]);
      const opsi_c = getVal(["opsi_c", "opsi c", "pilihan c", "c"]);
      const opsi_d = getVal(["opsi_d", "opsi d", "pilihan d", "d"]);
      const opsi_e = getVal(["opsi_e", "opsi e", "pilihan e", "e"]);
      const kunci = getVal(["kunci", "jawaban", "key", "answer"]).replace(/<[^>]+>/g, "").trim().toUpperCase();
      const rawType = getVal(["tipe", "jenis"]).replace(/<[^>]+>/g, "").trim();
      const bobot = getVal(["bobot", "poin", "skor", "points"]).replace(/<[^>]+>/g, "").trim() || "2.5";
      const toleransi = getVal(["toleransi", "tolerance"]).replace(/<[^>]+>/g, "").trim();
      const pembahasan = getVal(["pembahasan", "penjelasan", "explanation"]);

      const optCount = [opsi_a, opsi_b, opsi_c, opsi_d, opsi_e].filter(Boolean).length;
      const jenis_soal = normalizeWordQuestionType(rawType, optCount, kunci);

      questions.push({
        nomor,
        jenis_soal,
        soal,
        opsi_a,
        opsi_b,
        opsi_c,
        opsi_d,
        opsi_e,
        kunci,
        bobot,
        toleransi,
        pembahasan,
      });
    }
  }

  return questions;
}

/**
 * Parses questions from structured paragraph text (standard numbered question format).
 */
function parseParagraphBasedQuestions(html: string): WordQuestionItem[] {
  const questions: WordQuestionItem[] = [];

  // Split into paragraphs preserving img tags
  const paragraphs = html
    .split(/<\/p>/i)
    .map((p) => p.replace(/<p[^>]*>/i, "").trim())
    .filter((p) => p.length > 0);

  if (paragraphs.length === 0) return questions;

  let currentQ: Partial<WordQuestionItem> | null = null;
  let currentStemLines: string[] = [];
  let currentMode: "stem" | "opsi" | "pembahasan" = "stem";
  let currentOptionKey: "a" | "b" | "c" | "d" | "e" | null = null;

  const pushCurrentQuestion = () => {
    if (!currentQ || (!currentStemLines.length && !currentQ.soal)) return;

    const soal = currentQ.soal || currentStemLines.join("<br/>");
    const opsi_a = currentQ.opsi_a || "";
    const opsi_b = currentQ.opsi_b || "";
    const opsi_c = currentQ.opsi_c || "";
    const opsi_d = currentQ.opsi_d || "";
    const opsi_e = currentQ.opsi_e || "";
    const kunci = (currentQ.kunci || "").toUpperCase().trim();
    const optCount = [opsi_a, opsi_b, opsi_c, opsi_d, opsi_e].filter(Boolean).length;
    const rawType = currentQ.jenis_soal || "";
    const jenis_soal = normalizeWordQuestionType(rawType, optCount, kunci);

    questions.push({
      nomor: currentQ.nomor || `${questions.length + 1}`,
      jenis_soal,
      soal,
      opsi_a,
      opsi_b,
      opsi_c,
      opsi_d,
      opsi_e,
      kunci,
      bobot: currentQ.bobot || "2.5",
      toleransi: currentQ.toleransi || "",
      pembahasan: currentQ.pembahasan || "",
    });

    currentQ = null;
    currentStemLines = [];
    currentMode = "stem";
    currentOptionKey = null;
  };

  const questionStartRegex = /^(?:no\.?\s*|soal\s*)?(\d+)[\.\)\-\:]\s*(.*)$/i;
  const optionRegex = /^[A-E][\.\)\-\:]\s*(.*)$/i;
  const keyRegex = /^(?:kunci(?:\s*jawaban)?|jawaban|answer|key)[\s\:\=]+(.*)$/i;
  const typeRegex = /^(?:tipe(?:\s*soal)?|jenis(?:\s*soal)?|type)[\s\:\=]+(.*)$/i;
  const pointsRegex = /^(?:bobot(?:\s*poin|\s*skor)?|poin|points|skor)[\s\:\=]+(.*)$/i;
  const tolRegex = /^(?:toleransi|tolerance)[\s\:\=]+(.*)$/i;
  const explanationRegex = /^(?:pembahasan|penjelasan|explanation)[\s\:\=]+(.*)$/i;

  for (const para of paragraphs) {
    // Strip HTML for matching, but keep original for content (so inline images/formatting stay)
    const plainText = para.replace(/<[^>]+>/g, "").trim();

    // Check for Question Number start (e.g. "1. Nilai dari...")
    const qMatch = plainText.match(questionStartRegex);
    if (qMatch && !plainText.startsWith("A.") && !plainText.startsWith("B.")) {
      pushCurrentQuestion();
      currentQ = {
        nomor: qMatch[1],
      };
      // Remove the "1. " prefix from the original HTML
      const cleanedStem = para.replace(/^(?:<[^>]+>)*(?:no\.?\s*|soal\s*)?\d+[\.\)\-\:]\s*/i, "");
      currentStemLines = [cleanedStem];
      currentMode = "stem";
      continue;
    }

    if (!currentQ) {
      // If document started without "1. ", start first question automatically
      currentQ = { nomor: "1" };
      currentStemLines = [para];
      currentMode = "stem";
      continue;
    }

    // Check for Answer Key: "KUNCI: A" or "KUNCI JAWABAN: C"
    const keyMatch = plainText.match(keyRegex);
    if (keyMatch) {
      currentQ.kunci = keyMatch[1].trim();
      currentMode = "stem";
      continue;
    }

    // Check for Question Type: "TIPE: MCMA"
    const typeMatch = plainText.match(typeRegex);
    if (typeMatch) {
      currentQ.jenis_soal = typeMatch[1].trim();
      continue;
    }

    // Check for Points / Bobot: "BOBOT: 3"
    const ptMatch = plainText.match(pointsRegex);
    if (ptMatch) {
      currentQ.bobot = ptMatch[1].trim();
      continue;
    }

    // Check for Tolerance: "TOLERANSI: 0.05"
    const tolMatch = plainText.match(tolRegex);
    if (tolMatch) {
      currentQ.toleransi = tolMatch[1].trim();
      continue;
    }

    // Check for Explanation: "PEMBAHASAN: ..."
    const expMatch = plainText.match(explanationRegex);
    if (expMatch) {
      currentQ.pembahasan = para.replace(/^(?:<[^>]+>)*(?:pembahasan|penjelasan|explanation)[\s\:\=]+/i, "").trim();
      currentMode = "pembahasan";
      continue;
    }

    // Check for Option A-E: "A. Opsi teks"
    const optMatch = plainText.match(optionRegex);
    if (optMatch) {
      const optLetter = plainText[0].toUpperCase();
      const cleanedOpt = para.replace(/^(?:<[^>]+>)*[A-E][\.\)\-\:]\s*/i, "").trim();
      if (optLetter === "A") {
        currentQ.opsi_a = cleanedOpt;
        currentOptionKey = "a";
      } else if (optLetter === "B") {
        currentQ.opsi_b = cleanedOpt;
        currentOptionKey = "b";
      } else if (optLetter === "C") {
        currentQ.opsi_c = cleanedOpt;
        currentOptionKey = "c";
      } else if (optLetter === "D") {
        currentQ.opsi_d = cleanedOpt;
        currentOptionKey = "d";
      } else if (optLetter === "E") {
        currentQ.opsi_e = cleanedOpt;
        currentOptionKey = "e";
      }
      currentMode = "opsi";
      continue;
    }

    // Multiline continuation
    if (currentMode === "stem") {
      currentStemLines.push(para);
    } else if (currentMode === "opsi" && currentOptionKey) {
      const key = `opsi_${currentOptionKey}` as keyof WordQuestionItem;
      currentQ[key] = `${currentQ[key] || ""}<br/>${para}`;
    } else if (currentMode === "pembahasan") {
      currentQ.pembahasan = `${currentQ.pembahasan || ""}<br/>${para}`;
    }
  }

  // Push final question
  pushCurrentQuestion();

  return questions;
}

/**
 * Parses a Microsoft Word (.docx) file into the universal ParsedCsvResult.
 * Extracts text, math, options, answers, and embedded images seamlessly.
 */
export async function parseWordDocxFile(file: File): Promise<ParsedCsvResult> {
  const arrayBuffer = await file.arrayBuffer();

  // Convert docx to HTML with base64 embedded images preserved
  const conversionResult = await mammoth.convertToHtml(
    { arrayBuffer },
    {
      convertImage: mammoth.images.imgElement((image) => {
        return image.read("base64").then((imageBuffer) => {
          return {
            src: `data:${image.contentType};base64,${imageBuffer}`,
          };
        });
      }),
    },
  );

  const html = conversionResult.value;

  // Try parsing tables first; if no tables found or empty, parse paragraphs
  let questions = parseTableBasedQuestions(html);
  if (questions.length === 0) {
    questions = parseParagraphBasedQuestions(html);
  }

  // Map to Record<string, string>[] and string[][]
  const headers = [...QUESTION_IMPORT_HEADERS];
  const rows: Record<string, string>[] = [];
  const rawRows: string[][] = [];

  for (const q of questions) {
    const rowRecord: Record<string, string> = {
      nomor: q.nomor,
      jenis_soal: q.jenis_soal,
      soal: q.soal,
      opsi_a: q.opsi_a,
      opsi_b: q.opsi_b,
      opsi_c: q.opsi_c,
      opsi_d: q.opsi_d,
      opsi_e: q.opsi_e,
      kunci: q.kunci,
      bobot: q.bobot,
      toleransi: q.toleransi,
      pembahasan: q.pembahasan,
    };
    rows.push(rowRecord);

    const rowArray = headers.map((h) => rowRecord[h] || "");
    rawRows.push(rowArray);
  }

  return {
    headers,
    rows,
    rawRows,
    totalRows: rows.length,
  };
}
